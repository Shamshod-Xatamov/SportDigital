/* ---------- Avtomatik hisob-kitob (TZ 9-bo'lim formulalari) ---------- */

/** Marketing ROI = (daromad − xarajat) / xarajat × 100% */
export const calcRoi = (revenue, spend) =>
  spend > 0 ? ((revenue - spend) / spend) * 100 : 0;

/** CTR = bosishlar / ko'rsatishlar × 100% */
export const calcCtr = (clicks, impressions) =>
  impressions > 0 ? (clicks / impressions) * 100 : 0;

/** Conversion Rate = konversiyalar / bosishlar × 100% */
export const calcCr = (conversions, clicks) =>
  clicks > 0 ? (conversions / clicks) * 100 : 0;

/** Engagement Rate = (reaksiya + izoh + ulashish) / auditoriya × 100% */
export const calcEngagement = (channel) =>
  channel.audience > 0
    ? ((channel.reactions + channel.comments + channel.shares) / channel.audience) * 100
    : 0;

export const getChannel = (id) =>
  MARKETING_CHANNELS.find((item) => item.id === id) ?? MARKETING_CHANNELS[0];

export const getStatus = (id) =>
  CAMPAIGN_STATUSES.find((item) => item.id === id) ?? CAMPAIGN_STATUSES[0];
